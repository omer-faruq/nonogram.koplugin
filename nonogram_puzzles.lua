local index_by_id = {}
for i, entry in ipairs(Puzzles.list) do
    index_by_id[entry.id] = i
end

function Puzzles.count()
    return #Puzzles.list
end

--- Position of a picture in the list, or nil for an unknown id.
function Puzzles.indexOf(id)
    return index_by_id[id]
end

--- How many of the listed pictures are in the `solved` set ({ [id] = true }).
function Puzzles.solvedCount(solved)
    local count = 0
    for _, entry in ipairs(Puzzles.list) do
        if solved and solved[entry.id] then
            count = count + 1
        end
    end
    return count
end

--- The picture to play after `current_id`: the next unsolved one in list
-- order (wrapping around), or simply the next one once all are solved.
-- Returns the entry and its position.
function Puzzles.next(solved, current_id)
    local total = #Puzzles.list
    local start = index_by_id[current_id] or 0
    for step = 1, total do
        local i = (start + step - 1) % total + 1
        if not (solved and solved[Puzzles.list[i].id]) then
            return Puzzles.list[i], i
        end
    end
    local i = start % total + 1
    return Puzzles.list[i], i
end

return Puzzles
